//! **PBKDF2-HMAC-SHA-512**, RFC 8018 section 5.2 over the HMAC in `hmac.rs`.
//! Step 2 of `docs/roadmap/roadmap-user-keys.md`: a user's cluster key is
//! derived from their password with it (the first 32 bytes are the Ed25519
//! seed), and so is the version-2 `/etc/shadow` hash, so both cost a guesser
//! the same slow function.
//!
//! The iteration count is not chosen here. It is a wire constant every node
//! must agree on forever (the plan fixed 210,000 from a measurement on the
//! slowest guest), and it lives in `ninep-abi` from step 5. This takes it as a
//! parameter, and as a [`NonZeroU32`]: RFC 8018 requires a positive count, and a
//! count of zero would return the salt's MAC, not a derivation, so it cannot be
//! written.
//!
//! ## One iteration is two compressions
//!
//! The HMAC's inner and outer hashes are primed with the key pads once
//! (`hmac::primed_pads`) and copied per iteration, so each `U_j = HMAC(P,
//! U_{j-1})` costs the inner hash's single block (`U_{j-1}` and its padding fit
//! in 128 bytes) and the outer's. That is the figure the count was chosen from.
//!
//! ## What this does not do
//!
//! It does not wipe. Nothing in this crate does: the key-derived pad states and
//! the running block live on the caller's stack until overwritten, and clearing
//! secrets is the job of the code that holds them (the plan gives it to `login`,
//! which wipes its copy of the key, and to `netd`, which wipes held keys).

use core::num::NonZeroU32;

use crate::hmac::{primed_pads, HMAC_LEN};
use crate::sha512::Sha512;

/// One HMAC from the primed pads: the message `parts`, in order.
#[inline(always)]
fn mac(inner: &Sha512, outer: &Sha512, parts: &[&[u8]]) -> [u8; HMAC_LEN] {
    let mut i = inner.clone();
    for p in parts {
        i.update(p);
    }
    let mut o = outer.clone();
    o.update(&i.finalize());
    o.finalize()
}

/// Fill `out` with PBKDF2-HMAC-SHA-512 of `password` and `salt` at
/// `iterations`. Any output length; each 64-byte block is RFC 8018's `F` with
/// the block index counted from 1, and the last is truncated to fit.
///
/// A password longer than 128 bytes is hashed first, as HMAC requires, so
/// every length is accepted.
///
/// # Panics
///
/// On an output longer than `(2^32 - 1) * 64` bytes, which RFC 8018 section
/// 5.2 step 1 makes an error ("derived key too long"): past it the 32-bit block
/// index would wrap and the output would repeat. No caller comes near it; the
/// assert states the precondition rather than a comment.
pub fn pbkdf2_hmac_sha512(password: &[u8], salt: &[u8], iterations: NonZeroU32, out: &mut [u8]) {
    assert!(out.len() / HMAC_LEN < u32::MAX as usize, "PBKDF2: derived key too long");
    let (inner, outer) = primed_pads(password);
    for (i, chunk) in out.chunks_mut(HMAC_LEN).enumerate() {
        // INT(i): the block index, 32-bit big-endian, from 1. The assert
        // above keeps it below 2^32.
        let index = (i as u32 + 1).to_be_bytes();
        let mut u = mac(&inner, &outer, &[salt, &index]);
        let mut t = u;
        for _ in 1..iterations.get() {
            u = mac(&inner, &outer, &[&u]);
            for k in 0..HMAC_LEN {
                t[k] ^= u[k];
            }
        }
        chunk.copy_from_slice(&t[..chunk.len()]);
    }
}

