    /// Hex into `buf`, returning the decoded prefix.
    fn unhex<'a>(s: &str, buf: &'a mut [u8; 256]) -> &'a [u8] {
        let b = s.as_bytes();
        let n = b.len() / 2;
        assert!(n <= buf.len());
        for i in 0..n {
            buf[i] = (((b[i * 2] as char).to_digit(16).expect("hex") as u8) << 4)
                | ((b[i * 2 + 1] as char).to_digit(16).expect("hex") as u8);
        }
        &buf[..n]
    }

    fn derive(pw: &[u8], salt: &[u8], c: u32, len: usize) -> [u8; 256] {
        let mut out = [0u8; 256];
        pbkdf2_hmac_sha512(pw, salt, NonZeroU32::new(c).expect("positive"), &mut out[..len]);
        out
    }

    #[test]
    fn matches_hashlib() {
        for &(name, pw, salt, c, dk) in VECTORS {
            let (mut pb, mut sb, mut db) = ([0u8; 256], [0u8; 256], [0u8; 256]);
            let (pw, salt, dk) = (unhex(pw, &mut pb), unhex(salt, &mut sb), unhex(dk, &mut db));
            let got = derive(pw, salt, c, dk.len());
            assert_eq!(&got[..dk.len()], dk, "vector {name}");
        }
    }

    /// The step's controls, as a test: each vector must SEE a flipped bit in
    /// its password and in its salt, and an iteration count one either side.
    /// A table whose rows all passed with any of those changed would be a check
    /// that cannot fail. The 210,000 row, the count every node derives with,
    /// takes the password and salt flips like every other row; it skips only
    /// the ±1 runs, for time, since its ±1 is the same code as every other
    /// row's and they run it.
    #[test]
    fn every_vector_discriminates() {
        for &(name, pw, salt, c, dk) in VECTORS {
            let (mut pb, mut sb, mut db) = ([0u8; 256], [0u8; 256], [0u8; 256]);
            let (pw, salt, dk) = (unhex(pw, &mut pb), unhex(salt, &mut sb), unhex(dk, &mut db));
            let n = dk.len();
            if !pw.is_empty() {
                let mut p2 = [0u8; 256];
                p2[..pw.len()].copy_from_slice(pw);
                p2[0] ^= 1;
                assert_ne!(&derive(&p2[..pw.len()], salt, c, n)[..n], dk, "{name}: a flipped password bit");
            }
            if !salt.is_empty() {
                let mut s2 = [0u8; 256];
                s2[..salt.len()].copy_from_slice(salt);
                s2[salt.len() - 1] ^= 0x80;
                assert_ne!(&derive(pw, &s2[..salt.len()], c, n)[..n], dk, "{name}: a flipped salt bit");
            }
            if c > 10_000 {
                continue;
            }
            assert_ne!(&derive(pw, salt, c + 1, n)[..n], dk, "{name}: one iteration more");
            if c > 1 {
                assert_ne!(&derive(pw, salt, c - 1, n)[..n], dk, "{name}: one iteration fewer");
            }
        }
    }

    /// The seed this arc takes is the first 32 bytes of the 64-byte block, so
    /// a shorter output must be a PREFIX of a longer one, not a different
    /// derivation.
    #[test]
    fn a_shorter_output_is_a_prefix() {
        let long = derive(b"password", b"salt", 2, 128);
        for len in [1usize, 32, 63, 64, 65, 127] {
            assert_eq!(&derive(b"password", b"salt", 2, len)[..len], &long[..len], "length {len}");
        }
    }
