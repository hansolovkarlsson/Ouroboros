//! `dhepper/font8x8` on GitHub (Public Domain - based on Marcel Sondaar/IBM's
//! public-domain VGA fonts). Downloaded verbatim via `curl` rather than an
//! LLM-summarizing fetch, specifically to avoid silent transcription errors in
//! hex glyph data - the kind of corruption that wouldn't show up until a
//! specific character rendered wrong on screen.
//!
//! Each glyph is 8 bytes, one per pixel row, LSB-first: bit 0 of a row byte is
//! the glyph's *leftmost* pixel (confirmed against the source header's own
//! comments and cross-checked by eye against a few known letterforms below).

/// Glyph bitmap for ASCII code point `c`, if it's in the printable range
/// (0x20..=0x7E). Anything else (control codes, non-ASCII) has no glyph here.
pub fn glyph(c: u8) -> Option<&'static [u8; 8]> {
    if !(0x20..=0x7E).contains(&c) {
        return None;
    }
    Some(&FONT8X8_PRINTABLE[(c - 0x20) as usize])
}

